import mongoose from "mongoose";

const paymentAttemptSchema = new mongoose.Schema(
  {
    paymentId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Payment",
      required: true,
      index: true,
    },

    bookingId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Booking",
      required: true,
    },

    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },

    provider: {
      type: String,
      enum: ["PAYMOB"],
      required: true,
    },

    idempotencyKey: {
      type: String,
      required: true,
      trim: true,
      maxlength: 128,
    },

    initiationStatus: {
      type: String,
      enum: ["STARTED", "CREATED", "UNKNOWN", "FAILED"],
      default: "STARTED",
      required: true,
      index: true,
    },

    transactionStatus: {
      type: String,
      enum: ["PENDING", "SUCCEEDED", "FAILED", "CANCELLED"],
      default: "PENDING",
      required: true,
      index: true,
    },

    providerIntentionId: {
      type: String,
      default: null,
    },

    providerOrderId: {
      type: String,
      default: null,
    },

    providerTransactionId: {
      type: String,
      default: null,
    },

    amountMinor: {
      type: Number,
      required: true,
      min: 1,
      validate: Number.isSafeInteger,
    },

    currency: {
      type: String,
      enum: ["EGP"],
      default: "EGP",
      required: true,
    },

    // Never return this field by default or write it to logs.
    checkoutClientSecret: {
      type: String,
      default: null,
      select: false,
    },

    // Unique reference generated by our backend for this attempt.
    specialReference: {
      type: String,
      required: true,
      unique: true,
    },

    paidAt: {
      type: Date,
      default: null,
    },

    failureReason: {
      type: String,
      default: null,
      maxlength: 500,
    },

    reconciliationStatus: {
      type: String,
      enum: [
        "NOT_REQUIRED",
        "PENDING",
        "IN_PROGRESS",
        "RESOLVED",
        "MANUAL_REVIEW",
      ],
      default: "NOT_REQUIRED",
      required: true,
      index: true,
    },

    lastReconciledAt: {
      type: Date,
      default: null,
    },

    reconciliationAttempts: {
      type: Number,
      default: 0,
      min: 0,
    },

    // True means another attempt for this booking is blocked.
    blocksNewAttempt: {
      type: Boolean,
      default: true,
      required: true,
    },
  },
  { timestamps: true },
);

// The same user/key must not create two attempts.
paymentAttemptSchema.index({ userId: 1, idempotencyKey: 1 }, { unique: true });

// A provider transaction may be attached to only one attempt.
paymentAttemptSchema.index(
  { provider: 1, providerTransactionId: 1 },
  {
    unique: true,
    partialFilterExpression: {
      providerTransactionId: { $type: "string" },
    },
  },
);

paymentAttemptSchema.index({ paymentId: 1, createdAt: -1 });
paymentAttemptSchema.index({ reconciliationStatus: 1, updatedAt: 1 });

// At most one unresolved attempt that blocks a new attempt per booking.
paymentAttemptSchema.index(
  { bookingId: 1 },
  {
    unique: true,
    partialFilterExpression: { blocksNewAttempt: true },
  },
);

export default mongoose.model("PaymentAttempt", paymentAttemptSchema);
